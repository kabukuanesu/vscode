def _base_seed(roll):
    """Return a 32-bit seed derived from the roll number by SHA-256."""
    digest = hashlib.sha256(str(roll).strip().encode("utf-8")).hexdigest()
    return int(digest[:16], 16) % (2 ** 32)


def make_rng(roll, name):
    """Return an independent Generator for the named stream of this roll.

    Streams are independent so that adding an experiment later never shifts
    the numbers produced by an earlier one.
    """
    tag = hashlib.sha256(f"{str(roll).strip()}::{name}".encode("utf-8")).hexdigest()
    return np.random.default_rng(int(tag[:16], 16) % (2 ** 32))


def _normal_cdf(z):
    """Standard normal CDF, without SciPy."""
    return 0.5 * (1.0 + math.erf(z / math.sqrt(2.0)))


def _cell_mass(labels, prob):
    """Probability that the clean label is 1, under independent features."""
    total = 0.0
    for cell in range(8):
        bits = ((cell >> 2) & 1, (cell >> 1) & 1, cell & 1)
        mass = 1.0
        for bit, pr in zip(bits, prob):
            mass *= pr if bit else (1.0 - pr)
        total += mass * labels[cell]
    return total


def _has_parity_slice(labels):
    """True if some two-feature slice of the label function is XOR or XNOR.

    A linear threshold function stays a linear threshold function when
    restricted to a subcube, and XOR is not one.  So this condition is a
    sufficient certificate that the target is NOT additive in the features,
    which is what makes boosted stumps plateau in SQ4.
    """
    def at(a, b, c):
        return labels[(a << 2) | (b << 1) | c]

    for fixed in (0, 1):
        slices = (
            [at(0, 0, fixed), at(0, 1, fixed), at(1, 0, fixed), at(1, 1, fixed)],
            [at(0, fixed, 0), at(0, fixed, 1), at(1, fixed, 0), at(1, fixed, 1)],
            [at(fixed, 0, 0), at(fixed, 0, 1), at(fixed, 1, 0), at(fixed, 1, 1)],
        )
        for s00, s01, s10, s11 in slices:
            if s00 == s11 and s01 == s10 and s00 != s01:
                return True
    return False


def _cell_masses(prob):
    """Probability mass of each of the eight cells, indexed A*4 + B*2 + C."""
    masses = np.empty(8)
    for cell in range(8):
        bits = ((cell >> 2) & 1, (cell >> 1) & 1, cell & 1)
        masses[cell] = np.prod([pr if bit else 1.0 - pr
                                for bit, pr in zip(bits, prob)])
    return masses


def _is_xor_table(cells, labels):
    """True if the four cells, ordered (00, 01, 10, 11), carry XOR or XNOR."""
    a, b, c, d = (labels[i] for i in cells)
    return a == d and b == c and a != b


def _slices(var):
    """The two four-cell slices obtained by fixing one indicator to 0 and 1."""
    return [[c for c in range(8) if ((c >> (2 - var)) & 1) == bit]
            for bit in (0, 1)]


def _node_gini(cells, masses, p_one):
    """Mass and Gini impurity of the noisy label over a set of cells."""
    mass = masses[cells].sum()
    q = float((masses[cells] * p_one[cells]).sum() / mass)
    return mass, 2.0 * q * (1.0 - q)


def _best_gain(cells, free, masses, p_one):
    """Largest mass-weighted Gini gain over the free indicators."""
    mass, parent = _node_gini(cells, masses, p_one)
    best = 0.0
    for var in free:
        child = 0.0
        for bit in (0, 1):
            sub = [c for c in cells if ((c >> (2 - var)) & 1) == bit]
            sub_mass, sub_gini = _node_gini(sub, masses, p_one)
            child += sub_mass / mass * sub_gini
        best = max(best, mass * (parent - child))
    return best


def _greedy_safe(labels, masses):
    """Certify that greedy splitting on a finite sample will recover the target.

    Because the target is non-additive, some slice obtained by fixing one
    indicator is an XOR.  A root split on that indicator leaves a child with
    no marginal signal at all, and greedy then stalls or splits on noise.
    So the certificate requires (a) that the best root split on a SAFE
    indicator is strong, (b) that it beats every UNSAFE root split by a clear
    factor, so sampling noise cannot flip the choice, and (c) that each child
    of the safe root split has a strong split of its own.
    """
    p_one = _FLIP + (1.0 - 2.0 * _FLIP) * labels.astype(float)
    everything = list(range(8))
    gains = {v: _best_gain(everything, [v], masses, p_one) for v in range(3)}
    safe = [v for v in range(3)
            if not any(_is_xor_table(s, labels) for s in _slices(v))]
    unsafe = [v for v in range(3) if v not in safe]
    if not safe:
        return False
    root = max(safe, key=lambda v: gains[v])
    if gains[root] < _ROOT_FLOOR:
        return False
    if unsafe and max(gains[v] for v in unsafe) > _ROOT_RATIO * gains[root]:
        return False
    free = [v for v in range(3) if v != root]
    for cells in _slices(root):
        if labels[cells].min() == labels[cells].max():
            continue
        if _best_gain(cells, free, masses, p_one) < _GREEDY_FLOOR:
            return False
    return True


def _design(rng):
    """Draw the per-roll target.

    Each of the three informative features gets one threshold, so the feature
    space is cut into eight cells and the target is a Boolean function of the
    three indicators.  The function is redrawn until it is both roughly
    balanced and provably non-additive, which keeps the difficulty of the
    problem comparable across roll numbers: a depth-3 tree can always
    represent the target exactly, no additive model can, and greedy
    splitting on the population finds every one of its splits with a margin
    that survives finite-sample noise.
    """
    thresh = rng.uniform(-0.5, 0.5, size=3)
    prob = np.array([1.0 - _normal_cdf(v) for v in thresh])
    masses = _cell_masses(prob)

    labels = None
    for _ in range(2000):
        cand = rng.integers(0, 2, size=8)
        if (_has_parity_slice(cand)
                and 0.38 <= _cell_mass(cand, prob) <= 0.62
                and _greedy_safe(cand, masses)):
            labels = cand
            break
    if labels is None:                                  # pragma: no cover
        raise RuntimeError("no admissible target for this roll")

    return thresh, labels, rng.permutation(_N_FEATURES)


def _score(Z, thresh, labels, perm):
    """Clean label of every row, from the eight-cell target."""
    del perm
    bits = (Z[:, :3] > thresh[None, :]).astype(np.int64)
    cell = (bits[:, 0] << 2) | (bits[:, 1] << 1) | bits[:, 2]
    return labels[cell]


def _draw_features(rng, n):
    """Canonical feature matrix: three informative, three nuisance columns."""
    z0, z1, z2 = rng.normal(size=n), rng.normal(size=n), rng.normal(size=n)
    z3 = rng.normal(0.0, 1.0, size=n)
    z4 = rng.uniform(0.0, 100.0, size=n)
    z5 = rng.integers(0, 10, size=n).astype(float)
    return np.column_stack([z0, z1, z2, z3, z4, z5])


def _sample(rng, n, design):
    """Draw n labelled points; columns are permuted per roll."""
    Z = _draw_features(rng, n)
    clean = _score(Z, *design)
    y = np.where(rng.random(n) < _FLIP, 1 - clean, clean).astype(np.int64)
    return Z[:, design[-1]], y


def load_split(roll):
    """Return X_train, y_train, X_test, y_test for this roll number.

    X_train is (500, 6), X_test is (2000, 6), labels are in {0, 1}.

    Three of the six columns carry the signal and three are nuisance columns
    on deliberately different scales.  Which is which is not told to you, and
    you never need to know.  Ten per cent of the labels are flipped at random,
    so no model can do better than about 0.10 test error on this problem.
    """
    design = _design(make_rng(roll, "design"))
    X_train, y_train = _sample(make_rng(roll, "train"), _N_TRAIN, design)
    X_test, y_test = _sample(make_rng(roll, "test"), _N_TEST, design)
    return X_train, y_train, X_test, y_test


def _path_counts(n, n_zeros):
    """ways[k][v] = number of label suffixes from step k at excess v.

    The excess is (zeros so far) - (ones so far).  A path is admissible if the
    excess stays in [0, final] at every prefix, which is exactly the condition
    that no prefix and no suffix of the label sequence has a strict majority
    of ones.
    """
    final = 2 * n_zeros - n
    ways = [[0] * (final + 1) for _ in range(n + 1)]
    ways[n][final] = 1
    for k in range(n - 1, -1, -1):
        for v in range(final + 1):
            total = 0
            if v + 1 <= final:
                total += ways[k + 1][v + 1]
            if v - 1 >= 0:
                total += ways[k + 1][v - 1]
            ways[k][v] = total
    return ways, final


def _sample_path(rng, ways, n, final):
    """Sample one admissible label sequence uniformly from the strip."""
    labels = np.empty(n, dtype=np.int64)
    v = 0
    for k in range(n):
        up = ways[k + 1][v + 1] if v + 1 <= final else 0
        down = ways[k + 1][v - 1] if v - 1 >= 0 else 0
        if up + down == 0:
            raise RuntimeError("no admissible completion")
        if rng.random() < up / (up + down):
            labels[k], v = 0, v + 1
        else:
            labels[k], v = 1, v - 1
    return labels


def _best_gini_gain(y):
    """Largest Gini gain over all cuts of the ordered label sequence."""
    n = y.size
    c1 = np.cumsum(y)
    k = np.arange(1, n)
    l1 = c1[:-1]
    r1 = c1[-1] - l1
    pl = l1 / k
    pr = r1 / (n - k)
    parent = 2.0 * (c1[-1] / n) * (1.0 - c1[-1] / n)
    child = (k / n) * 2.0 * pl * (1.0 - pl) + ((n - k) / n) * 2.0 * pr * (1.0 - pr)
    return float(np.max(parent - child))


def tricky_node(roll):
    """Return X_node (100, 6), y_node (100,): one node from a partly grown tree.

    Only column 0 varies inside this node; the other five columns are constant,
    so column 0 supplies the only candidate splits.  The class counts are
    60 zeros and 40 ones.
    """
    rng = make_rng(roll, "node")
    ways, final = _path_counts(_NODE_N, _NODE_ZEROS)

    best_y, best_gain = None, -1.0
    for _ in range(40):
        cand = _sample_path(rng, ways, _NODE_N, final)
        gain = _best_gini_gain(cand)
        if gain > best_gain:
            best_y, best_gain = cand, gain

    x0 = np.sort(rng.uniform(-2.0, 2.0, size=_NODE_N))
    const = rng.uniform(-1.0, 1.0, size=_N_FEATURES - 1)
    X = np.column_stack([x0] + [np.full(_NODE_N, c) for c in const])
    return X, best_y
