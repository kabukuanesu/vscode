def student_seed(roll):
    """Return a deterministic non-negative integer seed derived from ``roll``.

    Parameters
    ----------
    roll : str
        Your roll number, e.g. ``"112201042"``. Case and surrounding
        whitespace are ignored.

    Returns
    -------
    int
        A seed in ``[0, 2**32)``, stable across machines and Python versions.
    """
    key = str(roll).strip().upper().encode("utf-8")
    return int(hashlib.sha256(key).hexdigest()[:8], 16)


def _rng(roll, stream):
    """Return an independent generator for one named data stream."""
    return np.random.default_rng([student_seed(roll), stream])


