def dataset_multiclass(roll):
    """Four classes in three dimensions, 75 points each.

    Returns
    -------
    X : ndarray, shape (300, 3)
    y : ndarray of int, shape (300,), values in {0, 1, 2, 3}

    Rows are grouped by class in increasing order.
    """
    rng = _rng(roll, 6)
    centres = np.array([[0.0, 0.0, 0.0],
                        [2.6, 0.4, -0.7],
                        [0.5, 2.4, 0.9],
                        [-1.8, 1.5, 2.2]])
    blocks, labels = [], []
    for k, centre in enumerate(centres):
        blocks.append(centre + rng.normal(size=(75, 3)) @ np.array(
            [[1.0, 0.0, 0.0], [0.35, 0.95, 0.0], [0.2, -0.3, 0.9]]).T)
        labels.append(np.full(75, k, dtype=int))
    return np.vstack(blocks), np.concatenate(labels)


# ---------------------------------------------------------------------------
# SQ5 -- generative vs discriminative
# ---------------------------------------------------------------------------

_D = 6
_MAHALANOBIS = 4.0
_RHO = 0.3


def _population():
    """Return (mean0, mean1, cholesky_factor) for the SQ5 population."""
    lower = np.eye(_D) + _RHO * np.tril(np.ones((_D, _D)), -1)
    cov = lower @ lower.T
    chol = np.linalg.cholesky(cov)
    precision = np.linalg.solve(cov, np.eye(_D))
    direction = np.ones(_D)
    direction = direction / np.sqrt(direction @ precision @ direction)
    return np.zeros(_D), _MAHALANOBIS * direction, chol


def _draw(rng, regime, n_points):
    mean0, mean1, chol = _population()
    labels = rng.integers(0, 2, size=n_points)
    features = np.where(labels[:, None] == 1, mean1, mean0)
    features = features + rng.normal(size=(n_points, _D)) @ chol.T
    if regime == "contaminated":
        hit = (rng.random(n_points) < 0.15) & (labels == 1)
        n_hit = int(hit.sum())
        if n_hit:
            displaced = mean1 - 6.0 * np.ones(_D)
            features[hit] = displaced + rng.normal(size=(n_hit, _D)) @ chol.T
    return features, labels


def sample_two_class(roll, regime, n_points, rep):
    """Draw one training set of size ``n_points`` from the SQ5 population.

    Parameters
    ----------
    roll : str
    regime : {"gaussian", "contaminated"}
        ``"gaussian"`` satisfies the equal-covariance Gaussian assumption
        exactly. ``"contaminated"`` replaces about 10% of class 1 with draws
        from a heavy-tailed component.
    n_points : int
    rep : int
        Repetition index. Independent across ``rep``, reproducible for fixed
        ``rep``.

    Returns
    -------
    X : ndarray, shape (n_points, 6)
    y : ndarray of int, shape (n_points,), values in {0, 1}
    """
    if regime not in ("gaussian", "contaminated"):
        raise ValueError("regime must be 'gaussian' or 'contaminated'")
    rng = np.random.default_rng(
        [student_seed(roll), 7, 0 if regime == "gaussian" else 1,
         int(n_points), int(rep)])
    return _draw(rng, regime, int(n_points))


def test_set(roll, regime):
    """Return a large, fixed test set from the same population as ``regime``.

    Returns
    -------
    X : ndarray, shape (20000, 6)
    y : ndarray of int, shape (20000,)

    The same test set is returned on every call for a given ``roll`` and
    ``regime``, so test errors measured at different training sizes are
    directly comparable.
    """
    if regime not in ("gaussian", "contaminated"):
        raise ValueError("regime must be 'gaussian' or 'contaminated'")
    rng = np.random.default_rng(
        [student_seed(roll), 8, 0 if regime == "gaussian" else 1])
    return _draw(rng, regime, 20000)
