# SQ1 / SQ2 / SQ6 -- three collinear classes
# ---------------------------------------------------------------------------


def dataset_masking(roll):
    """Three classes whose means lie on a straight line, 100 points each.

    Returns
    -------
    X : ndarray, shape (300, 2)
    y : ndarray of int, shape (300,), values in {0, 1, 2}

    Rows are grouped by class: rows 0-99 are class 0, 100-199 class 1,
    200-299 class 2. Class ``k`` is centred at ``(4k - 4, 0)``.
    """
    rng = _rng(roll, 1)
    blocks, labels = [], []
    for k, centre in enumerate((-4.0, 0.0, 4.0)):
        blocks.append(rng.normal([centre, 0.0], [0.8, 1.6], size=(100, 2)))
        labels.append(np.full(100, k, dtype=int))
    return np.vstack(blocks), np.concatenate(labels)


