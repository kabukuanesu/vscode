def dataset_margin(roll, kind):
    """A two-class, two-feature problem that is either separable or not.

    Parameters
    ----------
    roll : str
    kind : {"separable", "overlapping"}
        ``"separable"`` places the class centres far enough apart that a
        straight line divides them; ``"overlapping"`` does not.

    Returns
    -------
    X : ndarray, shape (80, 2)
    y : ndarray of int, shape (80,), values in {0, 1}, 40 of each
    """
    if kind not in ("separable", "overlapping"):
        raise ValueError("kind must be 'separable' or 'overlapping'")
    offset = 3.0 if kind == "separable" else 0.4
    rng = _rng(roll, 3 if kind == "separable" else 4)
    lower = rng.normal(-offset, 1.0, size=(40, 2))
    upper = rng.normal(+offset, 1.0, size=(40, 2))
    labels = np.concatenate([np.zeros(40, dtype=int), np.ones(40, dtype=int)])
    return np.vstack([lower, upper]), labels


def random_label_trial(roll, n_points, n_features, trial):
    """One draw of ``n_points`` points in general position with random labels.

    Parameters
    ----------
    roll : str
    n_points, n_features : int
    trial : int
        Index of the repetition. Different ``trial`` values give independent
        draws; the same value always gives the same draw.

    Returns
    -------
    X : ndarray, shape (n_points, n_features)
    y : ndarray of int, shape (n_points,), values in {0, 1}

    The labels are assigned by fair coin flip and carry no information about
    ``X`` whatsoever. That is the point.
    """
    rng = np.random.default_rng(
        [student_seed(roll), 5, int(n_points), int(n_features), int(trial)])
    return rng.normal(size=(n_points, n_features)), rng.integers(0, 2, size=n_points)


