# SQ4 -- badly scaled two-class problem
# ---------------------------------------------------------------------------


def dataset_scaling(roll):
    """A two-class problem whose three features live on wildly different scales.

    Returns
    -------
    X : ndarray, shape (400, 3)
        Raw, unstandardised features. Column 1 is roughly unit scale,
        column 2 is roughly 800x larger, column 3 roughly 250x smaller.
    y : ndarray of int, shape (400,), values in {0, 1}

    Standardising this design is the difference between a gradient method
    that finishes and one that does not.
    """
    rng = _rng(roll, 2)
    n = 400
    latent = rng.normal(size=(n, 2))
    x_1 = latent[:, 0]
    x_2 = latent[:, 1] * 800.0
    x_3 = latent[:, 0] * 0.004 + rng.normal(0.0, 0.001, n)
    features = np.column_stack([x_1, x_2, x_3])
    logits = features @ np.array([1.5, -0.004, 60.0]) - 0.3
    probs = 1.0 / (1.0 + np.exp(-logits))
    return features, (rng.random(n) < probs).astype(int)


